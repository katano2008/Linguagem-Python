numero = int(input('Escolha um número: ')) #Diz para que escolha um número
d = numero * 2 #Faz o calculo mostrando o dobro do número
t = numero * 3 #Faz o calculo mostrando o triplo do número
rq = numero ** 2 #Faz o calculo mostrando a potência do número
print('O número {} tem o dobro {}, o triplo {} e a raiz {}'.format(numero, d, t, rq)) #Mostra o resultado com resposta