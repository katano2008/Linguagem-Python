metros = int(input('Quantos metros deseja converter? ')) #Pergunta a medida na qual deseja converter
c = metros * 100 #Faz o calculo em centimetros, ou seja, converte
m = metros * 1000 #Faz o calculo em milimetros, ou seja, converte
print('A medida de {}m tem: {} centimentros e {} milimetros'.format(metros, c, m)) #Mostra o resultado final com a resposta